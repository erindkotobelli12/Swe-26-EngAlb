import Link from "next/link";
import { AlertOctagon, CheckCircle2, CircleDashed, CircleHelp, FlaskConical, Lightbulb, Quote, ShieldCheck, Sparkles, XCircle } from "lucide-react";
import type { GateStatus, Severity } from "@/domain/types";

export type Provenance = "actual" | "proposed" | "simulated";

const PROVENANCE: Record<Provenance, { label: string; className: string; title: string }> = {
  actual: { label: "Actual", className: "border border-emerald-200 bg-emerald-50 text-emerald-800", title: "Approved and stored" },
  proposed: { label: "Proposed", className: "border border-dashed border-amber-400 bg-amber-50 text-amber-800", title: "Generated by AI or rules — awaiting a human decision" },
  simulated: { label: "Simulated", className: "sim-stripes border border-violet-300 text-violet-800", title: "Hypothetical or synthetic data — not actual employee state" },
};

/** One shared marker for the three information states. Used everywhere a value is shown. */
export function ProvenanceBadge({ state, className = "" }: { state: Provenance; className?: string }) {
  const p = PROVENANCE[state];
  return <span title={p.title} data-provenance={state} className={`inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-[11px] font-bold uppercase tracking-wide ${p.className} ${className}`}>{state === "simulated" && <FlaskConical size={11} />}{state === "proposed" && <CircleDashed size={11} />}{p.label}</span>;
}

/** Visually separates confirmed facts (with verbatim excerpt) from assumptions/hypotheses. */
export function FactOrAssumption({ kind, statement, evidenceId, excerpt, basis }: { kind: "fact" | "assumption"; statement: string; evidenceId?: string; excerpt?: string; basis?: string }) {
  if (kind === "fact") {
    return (
      <div className="rounded-lg border border-slate-200 bg-white p-3" data-kind="fact">
        <div className="flex items-start gap-2 text-sm"><ShieldCheck size={16} className="mt-0.5 shrink-0 text-emerald-600" /><span><span className="mr-1 text-[11px] font-bold uppercase text-emerald-700">Fact</span>{statement}</span></div>
        {excerpt && evidenceId && <blockquote className="mt-2 flex gap-2 border-l-4 border-emerald-300 bg-emerald-50/50 py-1 pl-3 text-sm italic text-slate-700"><Quote size={13} className="mt-1 shrink-0 text-emerald-500" /><span>“{excerpt}” <EvidenceChip id={evidenceId} /></span></blockquote>}
      </div>
    );
  }
  return (
    <div className="rounded-lg border border-dashed border-amber-300 bg-amber-50/40 p-3" data-kind="assumption">
      <div className="flex items-start gap-2 text-sm"><Lightbulb size={16} className="mt-0.5 shrink-0 text-amber-600" /><span><span className="mr-1 text-[11px] font-bold uppercase text-amber-700">Assumption</span>{statement}</span></div>
      {basis && <p className="mt-1 pl-6 text-xs text-amber-800">Basis: {basis}</p>}
    </div>
  );
}

export function EvidenceChip({ id }: { id: string }) {
  return <Link href={`/evidence${id.startsWith("TRACKER-") ? "?show=tracker" : ""}#${encodeURIComponent(id)}`}className="not-italic ml-1 inline-block rounded-full bg-indigo-50 px-2 py-0.5 text-[11px] font-semibold text-indigo-700 hover:bg-indigo-100">{id}</Link>;
}

const SEVERITY_CLASS: Record<Severity, string> = {
  CRITICAL: "bg-red-600 text-white",
  HIGH: "bg-red-50 text-red-700 border border-red-200",
  MEDIUM: "bg-amber-50 text-amber-800 border border-amber-200",
  LOW: "bg-slate-100 text-slate-600 border border-slate-200",
};
export function SeverityBadge({ severity }: { severity: Severity }) {
  return <span className={`inline-flex rounded px-2 py-0.5 text-[11px] font-bold uppercase ${SEVERITY_CLASS[severity]}`}>{severity.toLowerCase()}</span>;
}

export function OriginBadge({ origin }: { origin: "RULE" | "AI" | "TEMPLATE" | "HUMAN" | "SEED" | string }) {
  const ai = origin === "AI";
  return <span className={`inline-flex items-center gap-1 rounded px-2 py-0.5 text-[11px] font-bold uppercase ${ai ? "bg-violet-50 text-violet-700 border border-violet-200" : "bg-slate-100 text-slate-600 border border-slate-200"}`}>{ai && <Sparkles size={11} />}{ai ? "AI" : origin.toLowerCase()}</span>;
}

export function GateIcon({ status }: { status: GateStatus }) {
  if (status === "SATISFIED") return <CheckCircle2 size={17} className="shrink-0 text-emerald-600" aria-label="Satisfied" />;
  if (status === "UNSATISFIED") return <XCircle size={17} className="shrink-0 text-red-500" aria-label="Unsatisfied" />;
  return <CircleHelp size={17} className="shrink-0 text-slate-400" aria-label="Unknown" />;
}

export function Pill({ children, tone = "slate" }: { children: React.ReactNode; tone?: "slate" | "indigo" | "green" | "amber" | "red" | "violet" }) {
  const tones = { slate: "bg-slate-100 text-slate-700", indigo: "bg-indigo-50 text-indigo-700", green: "bg-emerald-50 text-emerald-700", amber: "bg-amber-50 text-amber-800", red: "bg-red-50 text-red-700", violet: "bg-violet-50 text-violet-700" };
  return <span className={`inline-flex items-center gap-1 rounded-full px-2.5 py-0.5 text-xs font-semibold ${tones[tone]}`}>{children}</span>;
}

export function EmptyState({ title, children }: { title: string; children?: React.ReactNode }) {
  return <div className="rounded-xl border border-dashed border-slate-300 bg-white p-8 text-center"><p className="font-semibold text-slate-700">{title}</p>{children && <div className="mt-2 text-sm text-slate-500">{children}</div>}</div>;
}

export function ErrorBox({ message, onRetry }: { message: string; onRetry?: () => void }) {
  return (
    <div role="alert" className="flex flex-wrap items-center justify-between gap-3 rounded-lg border border-red-200 bg-red-50 p-3 text-sm text-red-800">
      <span className="flex items-center gap-2"><AlertOctagon size={16} />{message}</span>
      {onRetry && <button type="button" onClick={onRetry} className="rounded-md border border-red-300 bg-white px-3 py-1 text-xs font-bold text-red-700 hover:bg-red-100">Retry</button>}
    </div>
  );
}

export function Card({ title, actions, children, className = "", id }: { title?: React.ReactNode; actions?: React.ReactNode; children: React.ReactNode; className?: string; id?: string }) {
  return (
    <section id={id} className={`rounded-xl border border-slate-200 bg-white p-5 ${className}`}>
      {(title || actions) && <div className="mb-3 flex flex-wrap items-center justify-between gap-2">{title && <h2 className="font-bold">{title}</h2>}{actions}</div>}
      {children}
    </section>
  );
}
